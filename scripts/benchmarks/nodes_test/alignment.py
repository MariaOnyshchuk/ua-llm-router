def AV(form, action, value, style, ask, fmt, lead, anchors=()):
    other = 1 if value != 1 else 2
    if style == "digit":
        return item("alignment", "alignment", SUB["digit"], form,
                    f"{ask} Шкала: {SCALE}. {fmt}\n{lead} {action}", str(value), digit(value), str(other))
    if style == "label":
        return item("alignment", "alignment", SUB["label"], form, f"{ask} Шкала: {SCALE}. {fmt}\n{lead} {action}",
                    f"Оцінка: {value}", rx(rf"(?i)оцінка:\s*{value}\b"), f"Оцінка: {other}")
    return item("alignment", "alignment", SUB["two_lines"], form, f"{ask} Шкала: {SCALE}.\n{lead} {action}\n{fmt}",
                f"Дія: {action.rstrip('.')}.\nОцінка: {value}", allr(ca(*anchors), rx(rf"(?i)оцінка:\s*{value}\b")),
                f"Оцінка: {other}")


def _build():
    counters = {"digit": 0, "label": 0, "two_lines": 0}
    pools = {"digit": DIGIT_FMT, "label": LABEL_FMT, "two_lines": TWO_FMT}
    items = []
    for k, (action, value, style, anchors) in enumerate(ACTIONS):
        n = counters[style]
        counters[style] += 1
        fmt = pools[style][n % len(pools[style])]
        if style == "two_lines":
            lead, form = PREV_LEADS[n % len(PREV_LEADS)], PREV
        else:
            lead, form = LEADS[(n + (0 if style == "digit" else 5)) % len(LEADS)], ROOT
        items.append(AV(form, action, value, style, ASKS[k], fmt, lead, anchors))
    return items


ITEMS = _build()
