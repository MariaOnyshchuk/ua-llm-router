def main() -> None:
    counter: dict[str, int] = {}
    rows, errors = [], []
    for it in g.ITEMS:
        counter[it["class"]] = counter.get(it["class"], 0) + 1
        try:
            row = g.finish(it, counter[it["class"]])
        except AssertionError as exc:
            errors.append(f"[{it['class']} {counter[it['class']]}] {it['request'][:70]}…\n    {exc}")
            continue
        row["id"] = row["id"].replace("cg100-", "ct100-")
        row["split"] = "test"
        rows.append(row)
    if errors:
        raise SystemExit(f"{len(errors)} items fail the checks:\n" + "\n".join(errors))
    want = {"simple": 10, "chain": 30, "graph": 30, "parallel": 30}
    assert counter == want, counter
    assert len({r["request"] for r in rows}) == len(rows), "duplicate request"
    stad_here = [r["stad_id"] for r in rows if r["stad_id"]]
    assert len(stad_here) == len(set(stad_here)), "a STaD problem is used twice"

    # No overlap with the development set or v7.
    dev = [json.loads(line) for line in DEV.read_text(encoding="utf-8").splitlines()
           if line.strip() and not line.startswith("#")]
    v7_ids = {json.loads(line)["id"] for line in V7.read_text(encoding="utf-8").splitlines()
              if line.strip() and not line.startswith("#")}
    sources = lambda rs: {s.strip() for r in rs for s in (r.get("source_id") or "").split(",") if s.strip()}  # noqa: E731
    assert not ({r["request"] for r in rows} & {r["request"] for r in dev}), "request shared with the dev set"
    assert not (set(stad_here) & {r["stad_id"] for r in dev if r["stad_id"]}), "STaD problem shared with the dev set"
    assert not (sources(rows) & sources(dev)), "ZNO or Belebele item shared with the dev set"
    assert not (sources(rows) & v7_ids), "ZNO or Belebele item is in mixed_ua_v7"

    body = "\n".join(json.dumps(r, ensure_ascii=False) for r in rows) + "\n"
    fp = hashlib.sha256(body.encode()).hexdigest()[:16]
    head = (f"# graphs_mixed_100_test — simple 10, chain/graph/parallel 30 each, held-out test set; built by "
            f"scripts/benchmarks/build_graphs_mixed_100_test.py; fingerprint={fp}; frozen, run once after the planner is "
            f"frozen; generated, do not hand-edit\n")
    OUT.write_text(why_line(OUT.name) + head + body, encoding="utf-8")
    skills: dict[str, int] = {}
    for r in rows:
        for x in r["nodes"]:
            skills[x["skill"]] = skills.get(x["skill"], 0) + 1
    print(f"wrote {OUT.relative_to(ROOT)}: {len(rows)} items; node skills {skills}; STaD {len(stad_here)}; "
          f"corpus items {len(sources(rows))}; fingerprint {fp}")


if __name__ == "__main__":
    main()
